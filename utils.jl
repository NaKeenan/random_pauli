"""
    run_pauli_trial(N, num_steps, M, site, trial; save_dir="pauli_results", calc_weight_dist=true, save_coeffs=true)

Run a complete Pauli propagation simulation for a single trial.

This function sets up and runs a full simulation:
1. Creates initial operator Z_site
2. Defines operators to keep during truncation (all local Z operators)
3. Runs the time evolution
4. Saves results with metadata

The goal is to study how local magnetization Z_site spreads and correlates with
other sites under U(1) circuit dynamics.

# Arguments
- `N`: Number of qubits
- `num_steps`: Time steps to evolve
- `M`: Maximum Pauli terms to keep
- `site`: Initial site for Z operator
- `trial`: Random circuit realization
- `save_dir`: Directory to save results
- `calc_weight_dist`: Track weight distribution
- `save_coeffs`: Save full coefficients

# Returns
- Runtime of the simulation
"""
function run_pauli_trial(N, num_steps, M, site, trial; save_dir="pauli_results", calc_weight_dist=true, save_coeffs=true)
    mkpath(save_dir)

    keep_op = ps.Operator(N)
    for local_Z in single_Z_operators(N)
        keep_op += local_Z
    end

    O = ps.Operator(N)
    O += "Z", site

    println("Running PauliStrings: N=$N, M=$M, site=$site, trial=$trial")

    to = TimerOutput()
    runtime = @elapsed begin
        @timeit to "Pauli evolution" begin
            ret = two_point_correlators_random(N, num_steps, trial, O; M=M, noise=0, keep=keep_op, calc_weight_dist=calc_weight_dist, save_coeffs=save_coeffs)
            results, angle_list, weight_dist_array, coeffs = ret
        end
    end

    # Construct metadata dictionary
    params = Dict(
        "N" => N,
        "num_steps" => num_steps,
        "M" => M,
        "site" => site,
        "trial" => trial,
        "runtime" => runtime,
        "timestamp" => Dates.now(),
        "save_dir" => save_dir,
        "angle_list" => angle_list,
        "weight_dist_array_fix" => weight_dist_array,
        "coeffs" => coeffs
    )

    filepath = joinpath(save_dir, "pauli_M$(M)_site$(site)_trial$(trial)_N$(N).jld2")
    @save filepath results params

    return runtime
end


