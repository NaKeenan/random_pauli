"""
    load_angles(N::Int)

Load pre-generated random angles for N-qubit circuits.

Reads random angle parameters from random_archive/angles_N{N}.json.
These angles define the random U(1) circuits for different trials.

# Arguments
- `N`: Number of qubits

# Returns
- Array of angle dictionaries for multiple trials
"""
function load_angles(N::Int)
    filename = "random_archive/angles_N$(N).json"
    if !isfile(filename)
        error("File $filename does not exist.")
    end
    return JSON.parsefile(filename)
end

"""
    load_manual(N::Int)

Load manual circuit parameters from params.json.

# Arguments
- `N`: Number of qubits (must match value in params.json)

# Returns
- Dictionary of circuit parameters
"""
function load_manual(N::Int)
    filename = "params.json"
    if !isfile(filename)
        error("File $filename does not exist.")
    end
    data = JSON.parsefile(filename)
    if data["N"] != N
        error("Incorrect N value")
    else
        return data
    end
end

"""
    weight_dist(O)

Compute the weight distribution of a Pauli operator.

The weight of a Pauli string is the number of non-identity Pauli matrices.
This function computes how much amplitude (coefficient magnitude) is concentrated
at each weight level, providing insight into operator spreading.

# Arguments
- `O`: Pauli operator

# Returns
- Dictionary mapping weight → total amplitude at that weight
"""
function weight_dist(O)
    dist = Dict{typeof(ps.pauli_weight(O.strings[1])), typeof(O.coeffs[1])}()
    for I in eachindex(O.strings)
        key = ps.pauli_weight(O.strings[I])
        val = abs(O.coeffs[I])
        dist[key] = get(dist, key, zero(val)) + val
    end
    return dist
end

"""
    two_point_correlators_random(N, num_steps, trial, O; M=2^10, noise=0, keep=Operator(0), calc_weight_dist=true, save_coeffs=true)

Compute time evolution of correlation functions using random U(1) circuits.

This is the main simulation function. It evolves a Pauli operator through a random
U(1) circuit and computes correlation functions ⟨Z_i(t)⟩ = Tr[O(t) Z_i] / 2^N at each time step.

The Pauli propagation method allows efficient computation without storing the full
quantum state, making it feasible to study large systems.

# Arguments
- `N`: Number of qubits
- `num_steps`: Number of time steps to evolve
- `trial`: Which random circuit realization to use
- `O`: Initial Pauli operator (typically Z_site for some site)
- `M`: Truncation parameter for Pauli operator size
- `noise`: Noise level
- `keep`: Operators to preserve during truncation
- `calc_weight_dist`: Whether to track weight distribution evolution
- `save_coeffs`: Whether to save full operator coefficients

# Returns
- `correlators`: Time series of correlation functions ⟨Z_i(t)⟩
- `angle_list`: Circuit angles used
- `weight_dist_array`: Weight distributions at each time step
- `coeffs`: Full operator coefficients (if saved)
"""
function two_point_correlators_random(N, num_steps, trial, O; M=2^10, noise=0, keep=Operator(0), calc_weight_dist=true, save_coeffs=true)
    correlators = []
    weight_dist_array = []
    coeffs = []
    gate_list, angle_list = random_circuit(N, trial)
    all_local_Z = single_Z_operators(N)
    for t in 1:num_steps
        println("Time Step $t")
        correlators_t = [ps.trace_product(O, local_Z)/big(2)^N for local_Z in all_local_Z]
        push!(correlators, correlators_t)

        if calc_weight_dist
            push!(weight_dist_array, weight_dist(O))
        end

        if save_coeffs
            push!(coeffs, ps.op_to_strings(O))
        end

        O = apply_gate_list(O, gate_list, angle_list; M=M, noise=noise, keep=keep)
    end

    output = [real.(correlators), angle_list, weight_dist_array, coeffs]

    return output
end;

