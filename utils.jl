"""
PAULI PROPAGATION FOR U(1) CIRCUIT CORRELATION FUNCTIONS

This project studies correlation functions of U(1) symmetric quantum circuits using 
Pauli propagation methods. The key insights are:

1. U(1) SYMMETRY: Circuits preserve total magnetization Σᵢ Zᵢ, relevant for models
   like the Heisenberg model or systems with particle number conservation.

2. PAULI PROPAGATION: Instead of evolving the full quantum state |ψ(t)⟩, we evolve
   Pauli operators O(t) = U†(t) O U(t) using the identity:
   exp(iθP) O exp(-iθP) = cos(θ)O + i sin(θ)[P,O]
   This allows efficient computation of correlation functions ⟨Z_i(t)⟩.

3. CORRELATION FUNCTIONS: We compute ⟨Z_i(t)⟩ = Tr[O(t) Z_i]/2^N where O(0) = Z_j
   for some initial site j. This measures how local magnetization spreads.

4. TRUNCATION: The number of Pauli terms grows exponentially, so we truncate to
   the M largest terms while preserving important operators (local Z's).

5. WEIGHT DISTRIBUTION: We track how operator "weight" (number of non-identity
   Paulis) evolves, characterizing operator spreading and entanglement growth.
"""

### Gate application functions ###

"""
    apply_gate(O, P, θ; M=2^10, keep=Operator(0))

Apply a single quantum gate to a Pauli operator using the Pauli propagation method.

This function implements the core of Pauli propagation: given a Pauli operator O and 
a gate generated by Pauli generator P with angle θ, it computes the evolved operator
O' = exp(iθP) O exp(-iθP) using the formula:

O' = cos(θ)O + i*sin(θ)*[P,O]  (if [P,O] anticommutes with P)
O' = O                          (if [P,O] commutes with P)

# Arguments
- `O`: Input Pauli operator to evolve
- `P`: Pauli generator of the gate (single Pauli string)
- `θ`: Gate angle parameter
- `M`: Maximum number of Pauli terms to keep (truncation parameter)
- `keep`: Specific operators to always preserve during truncation

# Returns
- Evolved Pauli operator after applying the gate
"""
function apply_gate(O, P, θ; M=2^10, keep=Operator(0))
    @assert length(P.strings) == 1 "Gate must be generated by a single pauli generator"
    d = ps.emptydict(O)
    P = P.strings[1]
    for i in 1:length(O.strings)
        O_i, c_i = O.strings[i], O.coeffs[i]
        anticom = ps.anticommutator(O_i, P)

        if anticom[2] == 0
            c = c_i * cos(θ)
            ps.setwith!(+, d, O_i, c)
            p_n, k_n = ps.prod(P, O_i)

            c_n = sin(θ) * c_i * k_n * im
            ps.setwith!(+, d, p_n, c_n)
        
        else
            ps.setwith!(+, d, O_i, c_i)
        end

    end
    O_new = Operator(collect(keys(d)), collect(values(d)))
    O_new = ps.trim(O_new, M; keep=keep, keepnorm=false)
    return O_new
end

"""
    apply_gate_list(O, gate_list, angle_list; M=2^10, noise=0, keep=Operator(0))

Apply a sequence of quantum gates to a Pauli operator.

This function sequentially applies multiple gates to evolve the Pauli operator
through a quantum circuit. After all gates are applied, optional noise can be added.

# Arguments
- `O`: Initial Pauli operator
- `gate_list`: List of Pauli generators for each gate
- `angle_list`: List of angles corresponding to each gate
- `M`: Truncation parameter for maximum Pauli terms
- `noise`: Noise level to add after evolution
- `keep`: Operators to preserve during truncation

# Returns
- Final evolved Pauli operator after the full circuit
"""
function apply_gate_list(O, gate_list, angle_list; M=2^10, noise=0, keep=Operator(0))
    for i in 1:length(gate_list)
        O = apply_gate(O, gate_list[i], angle_list[i], M=M, keep=keep)
    end
    O = ps.add_noise(O, noise)
    return O
end

### Construction ###

"""
    single_Z_operators(N)

Generate all single-qubit Z operators for an N-qubit system.

Creates a list of N Pauli operators, each being a Z gate acting on a single qubit.
These are used as observables to compute correlation functions ⟨Z_i(t)⟩.

# Arguments
- `N`: Number of qubits in the system

# Returns
- Array of N Pauli operators, where ops[i] = Z_i
"""
function single_Z_operators(N)
    ops = Operator[]
    for i in 1:N
        O = Operator(N)
        O += "Z", i
        push!(ops, O)
    end
    return ops
end

"""
    random_circuit(N, trial)

Construct a random U(1) symmetric quantum circuit.

Generates a brick-layer circuit with random angles, implementing U(1) symmetric gates.
The circuit consists of:
1. Single-qubit Z rotations (θ1, θ2, θ3, θ4)
2. Two-qubit interactions: XX, YY, ZZ with strengths Jx, Jz

The circuit maintains U(1) symmetry by only using gates that preserve total magnetization.

# Arguments
- `N`: Number of qubits
- `trial`: Trial number (selects which random angles to use)

# Returns
- `gate_list`: List of Pauli generators for each gate
- `angle_list`: Corresponding angles for each gate
"""
function random_circuit(N, trial)
    angles = load_angles(N)[trial]
    gate_list = []
    angle_list = []

    for j in 1:2:N
        angles_bond = angles[j]
        θ1, θ2, Jx, Jz, θ3, θ4 = angles_bond["θ1"], angles_bond["θ2"], angles_bond["Jx"], angles_bond["Jz"], angles_bond["θ3"], angles_bond["θ4"]

        rot_1 = ps.Operator(N)
        rot_1 += "Z", j
        push!(gate_list, rot_1)
        push!(angle_list, θ1)

        rot_2 = ps.Operator(N)
        rot_2 += "Z", j+1
        push!(gate_list, rot_2)
        push!(angle_list, θ2)

        rot_xx = ps.Operator(N)
        rot_xx += "X", j, "X", j+1
        push!(gate_list, rot_xx)
        push!(angle_list, Jx)

        rot_yy = ps.Operator(N)
        rot_yy += "Y", j, "Y", j+1
        push!(gate_list, rot_yy)
        push!(angle_list, Jx)

        rot_zz = ps.Operator(N)
        rot_zz += "Z", j, "Z", j+1
        push!(gate_list, rot_zz)
        push!(angle_list, Jz)

        rot_3 = ps.Operator(N)
        rot_3 += "Z", j
        push!(gate_list, rot_3)
        push!(angle_list, θ3)

        rot_4 = ps.Operator(N)
        rot_4 += "Z", j+1
        push!(gate_list, rot_4)
        push!(angle_list, θ4)
    end

    for j in 2:2:N
        angles_bond = angles[j]
        θ1, θ2, Jx, Jz, θ3, θ4 = angles_bond["θ1"], angles_bond["θ2"], angles_bond["Jx"], angles_bond["Jz"], angles_bond["θ3"], angles_bond["θ4"]

        rot_1 = ps.Operator(N)
        rot_1 += "Z", j
        push!(gate_list, rot_1)
        push!(angle_list, θ1)

        rot_2 = ps.Operator(N)
        rot_2 += "Z", j%N+1
        push!(gate_list, rot_2)
        push!(angle_list, θ2)

        rot_xx = ps.Operator(N)
        rot_xx += "X", j, "X", j%N+1
        push!(gate_list, rot_xx)
        push!(angle_list, Jx)

        rot_yy = ps.Operator(N)
        rot_yy += "Y", j, "Y", j%N+1
        push!(gate_list, rot_yy)
        push!(angle_list, Jx)

        rot_zz = ps.Operator(N)
        rot_zz += "Z", j, "Z", j%N+1
        push!(gate_list, rot_zz)
        push!(angle_list, Jz)

        rot_3 = ps.Operator(N)
        rot_3 += "Z", j
        push!(gate_list, rot_3)
        push!(angle_list, θ3)

        rot_4 = ps.Operator(N)
        rot_4 += "Z", j%N+1
        push!(gate_list, rot_4)
        push!(angle_list, θ4)
    end
    return gate_list, angle_list
end

